import math

# Введення початкових даних
x = float(input("Введіть значення x: "))

# Обчислення частин виразу для зручності
чисельник_дробу = math.log(math.fabs(x + 1), 4)
знаменник_дробу = math.fabs(x + 1) + 0.7

# Загальна формула
y = 3**(-x) * math.sqrt(math.fabs(3.19 * x)) + (чисельник_дробу / знаменник_дробу)

# Виведення результату
print(f"Результат f(x) = {y}")
