# Запитуємо два двоцифрових числа у користувача
num1 = int(input("Введіть перше двоцифрове число: "))
num2 = int(input("Введіть друге двоцифрове число: "))

# Математично розбиваємо перше число на дві окремі цифри
# Наприклад, для 25: 25 // 10 дасть 2 (перша цифра)
digit1_1 = num1 // 10  
# 25 % 10 дасть залишок 5 (друга цифра)
digit1_2 = num1 % 10   

# Так само розбиваємо друге число
digit2_1 = num2 // 10
digit2_2 = num2 % 10

# Плюсуємо всі 4 знайдені цифри разом
total_sum = digit1_1 + digit1_2 + digit2_1 + digit2_2

# Показуємо результат на екрані
print("Сума всіх чотирьох цифр дорівнює:", total_sum)


